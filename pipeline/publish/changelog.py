"""The published changelog: one `## <version> (<day>)` entry per pack, newest first.

The file is not only for readers. `pipeline.cli._existing_versions` parses these headings to work
out the next pack's letter (`next_letter`), so the heading shape here is an interface, not a
style choice: `## `, one space, the pack version, one space, the day in parentheses. A heading
those two cannot parse would restart every day at `a` and drive the plugin version backwards.

The file is rebuilt from a parsed list of entries rather than edited in place, which is what makes
`keep` mean what it says whatever shape the existing file has -- including a hand-edited one.
"""

from __future__ import annotations

import re
from datetime import date
from pathlib import Path

# Anchored per line, so a `## ` inside a bullet or a fenced block is not mistaken for an entry.
_HEAD = re.compile(r"^## (\S+) \(\d{4}-\d{2}-\d{2}\)$", re.MULTILINE)

_HEADER = "# Changelog\n\nGenerated by the pipeline; newest first, last {keep} versions.\n"


def versions(path: Path) -> list[str]:
    """The pack versions the file records, newest first; empty if there is no file yet."""
    if not path.exists():
        return []
    return [m.group(1) for m in _HEAD.finditer(path.read_text())]


def _entries(text: str) -> list[str]:
    """The file's entries, each from its own heading up to the next one."""
    starts = [m.start() for m in _HEAD.finditer(text)]
    if not starts:
        return []
    bounds = zip(starts, [*starts[1:], len(text)], strict=True)
    return [text[start:end].strip("\n") + "\n" for start, end in bounds]


def _version_of(entry: str) -> str | None:
    """The pack version an entry's heading names."""
    match = _HEAD.match(entry)
    return match.group(1) if match else None


def prepend(path: Path, version: str, day: date, lines: list[str], keep: int = 30) -> None:
    """Put `version`'s entry at the top and keep the newest `keep` entries.

    Rewriting `version`'s existing entry rather than adding a second one makes this idempotent,
    which the promote job needs: a re-run of a job that already got as far as the changelog --
    after a failed `git push`, say -- would otherwise leave one version heading two entries, and
    `next_letter` counts headings.
    """
    existing = _entries(path.read_text() if path.exists() else "")
    entries = [e for e in existing if _version_of(e) != version]
    entry = f"## {version} ({day.isoformat()})\n" + "".join(f"- {line}\n" for line in lines)
    kept = [entry, *entries][:keep]
    path.write_text(_HEADER.format(keep=keep) + "\n" + "\n".join(kept))
